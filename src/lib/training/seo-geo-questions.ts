import type { TrainingQuestion } from "@/lib/training/catalog";

type Seed = {
  /** Aula do catálogo que a pergunta avalia. */
  l: string;
  /** mc = escolha única · ms = escolha múltipla · vf = verdadeiro/falso */
  t: "mc" | "ms" | "vf";
  p: string;
  /** Opções [texto, correta] (mc/ms). */
  o?: [string, boolean][];
  /** Resposta (vf). */
  a?: boolean;
  /** N.º da pergunta no documento, quando não é a posição (houve remoções). */
  n?: number;
  /** Nota de revisão — presente quando a resposta está por confirmar. */
  r?: string;
  /** Explicação lida na correção. */
  e?: string;
};

function bank(moduleId: string, seeds: Seed[]): TrainingQuestion[] {
  return seeds.map((s, i) => {
    const id = `${moduleId}-q${s.n ?? i + 1}`;
    const options =
      s.t === "vf"
        ? [
            { id: `${id}-v`, text: "Verdadeiro", isCorrect: s.a === true },
            { id: `${id}-f`, text: "Falso", isCorrect: s.a !== true },
          ]
        : (s.o ?? []).map(([text, isCorrect], k) => ({
            id: `${id}-o${k + 1}`,
            text,
            isCorrect,
          }));
    return {
      id,
      prompt: s.p,
      type:
        s.t === "vf"
          ? "true_false"
          : s.t === "ms"
            ? "multi_select"
            : "multiple_choice",
      order: i + 1,
      points: 1,
      options,
      explanation: s.e ?? null,
      lessonId: s.l,
      ...(s.r ? { needsReview: true, reviewNote: s.r } : {}),
    };
  });
}

